#!/usr/bin/env python3
"""Build the web version into web/. The author's site repo publishes that folder at https://zhukovskyi.space/tools/fileforge/
(~/Desktop/my_space/tools/sync_fileforge.py runs this script and copies web/).

  web/index.html     redirects to app/ (not published: /tools/fileforge/ is the site's product page)
  web/app/, vendor/, icons/   the app, exactly as in the extension
  web/privacy.html   PRIVACY.md rendered in the browser (the store listings link to it)
  web/app/site.webmanifest, web/app/sw.js   installable as an app and works offline
"""
import hashlib, json, pathlib, shutil

ROOT = pathlib.Path(__file__).resolve().parent.parent
SITE = ROOT / "web"

shutil.rmtree(SITE, ignore_errors=True)
SITE.mkdir()
for name in ["app", "vendor", "icons"]:
    shutil.copytree(ROOT / name, SITE / name, ignore=shutil.ignore_patterns(".DS_Store"))
shutil.copy2(ROOT / "PRIVACY.md", SITE / "PRIVACY.md")
(SITE / "docs" / "store").mkdir(parents=True)
shutil.copy2(ROOT / "docs" / "store" / "promo-marquee-1400x560.jpg", SITE / "docs" / "store" / "promo-marquee-1400x560.jpg")  # og:image

# --- installable, offline-capable web app: manifest + a service worker that precaches every file ---
version = json.loads((ROOT / "manifest.json").read_text())["version"]
index = SITE / "app" / "index.html"
html = index.read_text()
html = html.replace('<html lang="en">', '<html lang="en" data-site="1">', 1)
html = html.replace('<link rel="icon" href="../icons/icon32.png">', '<link rel="icon" href="../icons/icon32.png">\n  <link rel="manifest" href="site.webmanifest">', 1)
index.write_text(html)
(SITE / "app" / "site.webmanifest").write_text(json.dumps({
    "name": "FileForge: image, PDF & file tools",
    "short_name": "FileForge",
    "description": "Crop, resize, compress and convert images, merge and split PDFs, Markdown to PDF. Everything runs on your device.",
    "start_url": "./",
    "scope": "./",
    "display": "standalone",
    "background_color": "#1e222c",
    "theme_color": "#1e222c",
    "icons": [{"src": "../icons/icon256.png", "sizes": "256x256", "type": "image/png"},
              {"src": "../icons/icon512.png", "sizes": "512x512", "type": "image/png", "purpose": "any maskable"}],
    # Installed as an app, FileForge appears in the OS "Open with" menu for these types (app.js: launchQueue).
    "file_handlers": [
        {"action": "./", "accept": {"image/jpeg": [".jpg", ".jpeg", ".jfif"], "image/png": [".png"], "image/webp": [".webp"],
                                    "image/gif": [".gif"], "image/bmp": [".bmp"], "image/svg+xml": [".svg"], "image/avif": [".avif"],
                                    "image/heic": [".heic"], "image/heif": [".heif"]}},
        {"action": "./", "accept": {"application/pdf": [".pdf"]}},
        {"action": "./", "accept": {"text/markdown": [".md", ".markdown"], "text/csv": [".csv"], "application/json": [".json"]}},
    ],
}, indent=2) + "\n")

# The OCR engine and its language models (~8 MB) and the background-removal model with ONNX Runtime (~75 MB) are
# files most visits never need: they are left out of the precache and cached the first time their tool asks for
# them (the LAZY cache survives version updates).
# Bump the number in LAZY below whenever vendor/ocr or vendor/rembg changes, or returning visitors keep the old files.
LAZY_PREFIXES = ("vendor/ocr/", "vendor/rembg/")
files = sorted(p for p in SITE.rglob("*") if p.is_file() and p.suffix not in {".webmanifest"} and p.name != "sw.js"
               and not p.relative_to(SITE).as_posix().startswith(LAZY_PREFIXES))
# "sw2" stands for the worker code below: change it when that code changes, so the cache name changes too.
digest = hashlib.sha256(b"sw2" + b"".join(p.read_bytes() for p in files)).hexdigest()[:12]
# "./" is the address people actually open (…/app/, the manifest's start_url): without it nothing starts offline.
urls = ["./"] + ["../" + p.relative_to(SITE).as_posix() for p in files]  # relative to app/
(SITE / "app" / "sw.js").write_text(f"""// FileForge offline cache, generated by scripts/build_web_app.py for version {version}.
const CACHE = "fileforge-{version}-{digest}";
const LAZY = "fileforge-lazy-1";
const FILES = {json.dumps(urls)};
self.addEventListener("install", (e) => {{
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES.map((u) => new Request(u, {{ cache: "reload" }})))).then(() => self.skipWaiting()));
}});
self.addEventListener("activate", (e) => {{
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE && k !== LAZY).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
}});
self.addEventListener("fetch", (e) => {{
  if (e.request.method !== "GET") return;
  e.respondWith(caches.match(e.request, {{ ignoreSearch: true }}).then((hit) => hit || fetch(e.request).then((res) => {{
    if (res.ok && {json.dumps(["/" + x for x in LAZY_PREFIXES])}.some((p) => new URL(e.request.url).pathname.includes(p))) {{ const copy = res.clone(); caches.open(LAZY).then((c) => c.put(e.request, copy)); }}
    return res;
  }}).catch((err) => {{
    // Offline and not in the cache: any page address inside the app still opens the app itself.
    if (e.request.mode !== "navigate") throw err;
    return caches.match("./index.html").then((page) => page || Promise.reject(err));
  }})));
}});
""")

(SITE / "index.html").write_text("""<!doctype html>
<meta charset="utf-8">
<title>FileForge</title>
<meta http-equiv="refresh" content="0; url=app/">
<link rel="canonical" href="app/">
<p>Opening <a href="app/">FileForge</a>…</p>
""")

(SITE / "privacy.html").write_text("""<!doctype html>
<html lang="en">
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>FileForge privacy policy</title>
<link rel="icon" href="icons/icon32.png">
<style>
  body { max-width: 720px; margin: 40px auto; padding: 0 16px; font: 16px/1.6 system-ui, sans-serif; color: #1f2328; }
  @media (prefers-color-scheme: dark) { body { background: #0d1117; color: #e6edf3; } a { color: #79b8ff; } }
  code { font-size: 0.9em; }
</style>
<main id="doc">Loading…</main>
<script src="vendor/marked.min.js"></script>
<script>
  fetch("PRIVACY.md").then(r => r.text()).then(md => { document.getElementById("doc").innerHTML = marked.parse(md); });
</script>
</html>
""")
(SITE / ".nojekyll").write_text("")
print(f"wrote {SITE.relative_to(ROOT)}/")
